"""Independent exact verification of the extremal packings stored in groups/*_results.json.

This script does NOT use the search code (geom.py, surface.py, batch.py). For every surface D/K it checks:
  (1) the exact matrices a, b, c of field.py are the reflections described in Section 2 of the paper
      (numerical values of the entries) and satisfy the Coxeter relations exactly;
  (2) every stored side pairing s (a word in a, b, c) lies in K, using only the permutation action of
      Delta^pm on the cosets of K exported by GAP (groups/*.jsonl); for a double cover K^+ the word must also
      have even length;
  (3) the side pairings generate K: GAP computes the index of <side pairings> in Delta^pm(2,3,N);
  (4) for every stored extremal packing, with exact alpha in M_2(L_N) and words w_s:
          s * alpha = +- alpha * w_s     (exact identity in M_2(L_N)),   det(alpha) != 0,
      which means alpha^-1 K alpha < Delta^pm, i.e. the points alpha(g O), g in Delta^pm, are the centres of an
      extremal packing of D/K;
  (5) the stored number of packings equals the number of verified matrices alpha, and these give pairwise
      different packings: alpha_i^-1 alpha_j is not in Delta^pm (numerical chamber algorithm, 40 digits).
What remains outside this check is the completeness of the list (that there are no further packings), which
relies on the search of surface.py (Sections 3-4 of the paper).

Usage:  python3 verify_packings.py                 all families (about one minute)
        python3 verify_packings.py fuchs_N9 21     a single surface (class number as in the paper)
"""
import json, sys, subprocess, tempfile, os
import mpmath as mp
from field import Field, pari

FAMILIES = ['nec_N12', 'nec_N9', 'nec_N8', 'nec_N7', 'fuchs_N18', 'fuchs_N12', 'fuchs_N10', 'fuchs_N9',
            'fuchs_N8', 'fuchs_N7', 'nec_N18']


def check_field(F, N):
    s = mp.sin(mp.pi / N)
    u = mp.exp(mp.acosh(1 / (2 * s)))
    exp = {'a': [[1, 0], [0, -1]], 'b': [[0, 1 / u], [u, 0]], 'c': [[-mp.cos(mp.pi / N), s], [s, mp.cos(mp.pi / N)]]}
    for g in 'abc':
        M = F.mat_num(F.gens[g])
        assert max(abs(M[i][j] - exp[g][i][j]) for i in range(2) for j in range(2)) < 1e-30, 'matrix %s' % g
        assert F.is_scalar(F.gens[g] * F.gens[g]), '%s^2' % g
    A, B, C = F.gens['a'], F.gens['b'], F.gens['c']
    assert F.is_scalar((A * B) ** 2) and F.is_scalar((B * C) ** 3) and F.is_scalar((C * A) ** N)
    assert not any(F.is_scalar((C * A) ** j) for j in range(1, N)), '(ca) must have order exactly N'


def apply(perm, p, word):
    for ch in word:
        p = perm[ch][p]
    return p


def gap_indices(N, wordlists):
    """index in Delta^pm(2,3,N) of the subgroup generated by each list of words"""
    lines = ['F := FreeGroup("a","b","c");; a:=F.1;; b:=F.2;; c:=F.3;;',
             'G := F / [a^2, b^2, c^2, (a*b)^2, (b*c)^3, (c*a)^%d];; a:=G.1;; b:=G.2;; c:=G.3;;' % N,
             'res := [];;']
    for ws in wordlists:
        gens = ', '.join('*'.join(ch for ch in w) if w else 'One(G)' for w in ws)
        lines.append('Add(res, Index(G, Subgroup(G, [%s])));;' % gens)
    lines.append('Print(res, "\\n");; QUIT;')
    with tempfile.NamedTemporaryFile('w', suffix='.g', delete=False) as f:
        f.write('\n'.join(lines))
        fn = f.name
    out = subprocess.run(['gap', '-q', '-b', fn], capture_output=True, text=True,
                         stdin=subprocess.DEVNULL).stdout   # no input: on an error GAP stops instead of waiting
    os.unlink(fn)
    return json.loads(out.replace('\n', '').replace('\\', ''))


def check_surface(F, rec, perm, d, label):
    """returns (#packings verified, side-pairing words); raises AssertionError on any failure"""
    sps = rec['sidepairings']
    for w in sps:
        assert apply(perm, 0, w) == 0, '%s: side pairing %s not in K' % (label, w)
        if perm.get('plus_only'):
            assert len(w) % 2 == 0, '%s: side pairing %s reverses orientation' % (label, w)
    S = [F.word_matrix(w) for w in sps]
    alphas = []
    for P in rec['packings']:
        al = pari(P['alpha_exact'])
        assert F.det(al) != 0
        assert len(P['words']) == len(sps)
        for Sm, w in zip(S, P['words']):
            W = F.word_matrix(w)
            L, R = Sm * al, al * W
            assert L == R or L == -R, '%s: the exact identity fails for a side pairing' % label
        alphas.append(al)
    assert len(alphas) == rec['n_packings'], '%s: number of packings' % label
    # (5) distinct packings: alpha_i^-1 alpha_j must not lie in Delta^pm (two packings coincide iff their
    # sets of centres coincide iff alpha_j Delta^pm = alpha_i Delta^pm, Delta^pm being maximal)
    for i in range(len(alphas)):
        for j in range(i + 1, len(alphas)):
            assert not in_triangle_group(F, minv(F.mat_num(alphas[i])), F.mat_num(alphas[j])), \
                '%s: packings %d and %d coincide' % (label, i, j)
    return len(alphas), sps


# ---- numerical membership test in Delta^pm (chamber algorithm), independent of geom.py ----
def mmul(X, Y):
    return [[X[0][0] * Y[0][0] + X[0][1] * Y[1][0], X[0][0] * Y[0][1] + X[0][1] * Y[1][1]],
            [X[1][0] * Y[0][0] + X[1][1] * Y[1][0], X[1][0] * Y[0][1] + X[1][1] * Y[1][1]]]


def minv(X):
    return [[X[1][1], -X[0][1]], [-X[1][0], X[0][0]]]


def act(M, z):
    det = M[0][0] * M[1][1] - M[0][1] * M[1][0]
    zz = z if det > 0 else mp.conj(z)
    return (M[0][0] * zz + M[0][1]) / (M[1][0] * zz + M[1][1])


def side(M, z):
    """sign of f(z) = gamma |z|^2 + 2 delta x - beta; its zero set is the mirror of the reflection M"""
    return mp.sign(M[1][0] * abs(z) ** 2 + 2 * M[1][1] * z.real - M[0][1])


def fixed_point(M):
    a, b, c, d = M[0][0], M[0][1], M[1][0], M[1][1]
    z = ((a - d) + mp.sqrt(mp.mpc((a + d) ** 2 - 4))) / (2 * c)
    return z if z.imag > 0 else mp.conj(z)


_T0 = {}


def triangle(F):
    """generic interior point p0 of the fundamental triangle and the side signs"""
    if F.N not in _T0:
        g = F.gens_num
        O, m, v = mp.mpc(0, 1), fixed_point(mmul(g['a'], g['b'])), fixed_point(mmul(g['b'], g['c']))
        p0 = (O + m + v) / 3
        sg = {'a': side(g['a'], v), 'b': side(g['b'], O), 'c': side(g['c'], m)}
        assert all(side(g[x], p0) == sg[x] != 0 for x in 'abc'), 'p0 not inside the triangle'
        _T0[F.N] = (p0, sg)
    return _T0[F.N]


def in_triangle_group(F, X, Y):
    """is the isometry X*Y (numeric matrices) an element of Delta^pm?"""
    p0, sg = triangle(F)
    g = F.gens_num
    M = mmul(X, Y)
    z = act(M, p0)
    H = M
    for _ in range(100000):
        bad = [x for x in 'abc' if side(g[x], z) != sg[x]]
        if not bad:
            break
        z = act(g[bad[0]], z)
        H = mmul(g[bad[0]], H)
    if abs(z - p0) > mp.mpf(10) ** -15:
        return False
    sc = mp.sqrt(abs(H[0][0] * H[1][1] - H[0][1] * H[1][0]))
    return max(abs(H[0][1]), abs(H[1][0]), abs(H[0][0] - H[1][1])) / sc < mp.mpf(10) ** -15 and \
        mp.sign(H[0][0] * H[1][1] - H[0][1] * H[1][0]) > 0


def run(families, only=None):
    total = 0
    for fam in families:
        fn = 'groups/%s_results.json' % fam
        if not os.path.exists(fn):
            continue
        N = int(fam.split('_N')[1])
        F = Field(N)
        check_field(F, N)
        Wn = F.mat_num(F.word_matrix('cabcacbcab'))
        assert in_triangle_group(F, F.gens_num['a'], Wn), 'self-test of the membership test failed'
        assert not in_triangle_group(F, [[mp.mpf(2), 0], [0, mp.mpf(1) / 2]], Wn), 'self-test failed'
        groups = [json.loads(l) for l in open('groups/%s.jsonl' % fam) if l.strip()]
        res = json.load(open(fn))
        todo = []
        for i, (g, rec) in enumerate(zip(groups, res)):
            if only is not None and i + 1 != only:
                continue
            perm = {ch: [x - 1 for x in g[ch]] for ch in 'abc'}
            n, sps = check_surface(F, rec, perm, g['d'], rec['label'])
            todo.append((sps, g['d'], rec['label'], n))
            if rec.get('double_cover'):
                dc = rec['double_cover']
                # K^+ = K cap Delta: words in K of even length
                pp = dict(perm); pp['plus_only'] = True
                n2, sps2 = check_surface(F, dc, pp, 2 * g['d'], dc['label'])
                todo.append((sps2, 2 * g['d'], dc['label'], n2))
            if only is not None:
                print('%s: %d packings verified' % (rec['label'], n))
                for j, P in enumerate(rec['packings']):
                    print('   packing %d: centre %s (disc model), d(O, centre) = %s' % (j, P['centre_disc'], P['dist_to_origin']))
        idx = gap_indices(N, [t[0] for t in todo])
        for (sps, d, label, n), ix in zip(todo, idx):
            assert ix == d, '%s: side pairings generate a subgroup of index %d, expected %d' % (label, ix, d)
            total += n
        print('%-10s %3d surfaces: field OK, side pairings in K and generating K, %d packings verified' % (
            fam, len(todo), sum(t[3] for t in todo)))
    return total


if __name__ == '__main__':
    if len(sys.argv) == 3:
        run([sys.argv[1]], int(sys.argv[2]))
    else:
        from outfile import tee
        tee('groups/verify_packings.txt')
        print('packings verified:', run(FAMILIES))
