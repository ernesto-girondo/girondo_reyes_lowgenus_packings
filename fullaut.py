"""Full automorphism group of D/K (including anticonformal) using the hidden packings:
Aut(X) = union over packings j of { g in alpha_j Delta^pm : g normalises K }, and such g exists iff
K_j := alpha_j^{-1} K alpha_j (generated by the words w_s) is Delta^pm-conjugate to K.
Also: involutions and their fixed points (Weierstrass points)."""
import json, sys
import mpmath as mp
from collections import Counter
from geom import Geometry, to_disc, hdist, act, mmul, minv, mdet
from surface import Surface
from gapiface import coset_action_from_words, reduce_word
from batch import canonical_key, automorphisms, parity_and_words

mp.mp.dps = 40


def involution_fixed_points(S, aut):
    """for an induced automorphism phi_j: number of fixed points on the surface and their nature.
    conformal fixed points <-> triangles p with p^(ab) = phi(p) (lift is a conjugate of ab: fixed point = edge midpoint)
    or p^(bc)=phi(p) / p^((bc)^2) (vertex, order 3) or p^((ca)^m) (polygon centre)."""
    d = S.d
    par, word = parity_and_words(S.perm, d)
    j = aut['j']
    phi = [S.apply(j, word[p]) for p in range(d)]
    res = {}
    # edge midpoints: 4 triangles around each midpoint
    res['midpoints'] = sum(1 for p in range(d) if S.apply(p, 'ab') == phi[p]) // 4
    res['vertices'] = sum(1 for p in range(d) if S.apply(p, 'bc') == phi[p] or S.apply(p, 'bcbc') == phi[p]) // 6
    res['centres'] = sum(1 for p in range(d) if any(S.apply(p, 'ca' * m) == phi[p] for m in range(1, S.N))) // (2 * S.N)
    return res


def analyse_full(G, action, label):
    S = Surface(G, action, label=label)
    S.analyse(verbose=False)
    key0 = canonical_key(S.perm, S.d)
    auts = automorphisms(S)
    n_ind = len(auts)
    print('== %s: N=%d k=%d packings=%d induced |Aut|=%d' % (label, S.N, S.k, len(S.packings), n_ind))
    orbit_sizes = []
    extra = 0
    i0 = mp.mpc(0, 1)
    for P in S.packings:
        if G.reduce(P['alpha']) is not None:
            print('   packing 0 (original): stabiliser = induced automorphisms, order', n_ind)
            continue
        act_j = coset_action_from_words(S.N, [reduce_word(w) for w in P['words']])
        same = act_j['d'] == S.d and canonical_key({'a': act_j['a'], 'b': act_j['b'], 'c': act_j['c']}, act_j['d']) == key0
        print('   packing at %s (d=%s): K_j index %d, Delta^pm-conjugate to K: %s' % (
            mp.nstr(to_disc(P['z']), 8), mp.nstr(hdist(i0, P['z']), 6), act_j['d'], same))
        if same:
            extra += 1
    total = n_ind * (1 + extra)
    conf = sum(1 for a in auts if a['parity'] == 0)
    anti = n_ind - conf
    print('   |Aut(X)| (incl. anticonformal) = %d x %d = %d ;  induced conformal = %d, anticonformal = %d' % (n_ind, 1 + extra, total, conf, anti))
    print('   => |Aut^+(X)| = %d' % (total // 2 if anti > 0 or extra else total))
    # induced involutions and fixed points
    for a in auts:
        if a['order'] == 2 and a['parity'] == 0:
            fp = involution_fixed_points(S, a)
            print('   conformal involution j=%d word=%s fixed points: %s' % (a['j'], a['word'], fp))
    orders = Counter((a['order'], a['parity']) for a in auts)
    print('   induced automorphisms (order, parity): %s' % dict(orders))
    return S


