"""Isometries between packings and between surfaces (Theorem 6.1, last two sentences; Theorem 6.3(i),(vi)).

For a surface D/K and an extremal packing P_j given by an inclusion K < alpha_j Delta^pm alpha_j^-1, the group
K_j = alpha_j^-1 K alpha_j < Delta^pm is generated by the words w_s stored in the results file. Delta^pm being a
maximal NEC group:
  * an isometry of D/K maps the packing P_0 (centre O) to P_j  iff  K_j is Delta^pm-conjugate to K;
  * if K_j is Delta^pm-conjugate to another class K', then D/K and D/K' are isometric.
This script computes the Delta^pm-class of every K_j of every surface of the paper (and of the double covers) from
the stored words only -- no search is re-run -- and reports, per family:
  - the surfaces on which the isometry group is NOT transitive on the set of extremal packings;
  - the pairs of different classes that give isometric surfaces.
Output: groups/isometry_orbits.txt (also printed). About 2 minutes (one GAP session per family).
"""
import json, os, subprocess, tempfile
from batch import canonical_key
from gapiface import reduce_word

FAMILIES = ['nec_N12', 'nec_N9', 'nec_N8', 'nec_N7', 'fuchs_N18', 'fuchs_N12', 'fuchs_N10', 'fuchs_N9',
            'fuchs_N8', 'fuchs_N7']

GAP = r"""
F := FreeGroup("a","b","c");; a := F.1;; b := F.2;; c := F.3;;
G := F / [a^2, b^2, c^2, (a*b)^2, (b*c)^3, (c*a)^%d];; a := G.1;; b := G.2;; c := G.3;;
W := function(s) local w, ch; w := One(G);
  for ch in s do if ch = 'a' then w := w*a; elif ch = 'b' then w := w*b; else w := w*c; fi; od; return w; end;;
out := OutputTextFile("%s", false);; SetPrintFormattingStatus(out, false);;
for gens in %s do
  K := Subgroup(G, List(gens, W));; hom := FactorCosetAction(G, K);; d := Index(G, K);;
  AppendTo(out, "{\"d\":", d, ",\"a\":", ListPerm(Image(hom, a), d), ",\"b\":", ListPerm(Image(hom, b), d),
           ",\"c\":", ListPerm(Image(hom, c), d), "}\n");
od;
CloseStream(out);; QUIT;
"""


def coset_actions(N, wordlists):
    with tempfile.TemporaryDirectory() as td:
        outp = os.path.join(td, 'out.jsonl')
        gl = '[' + ', '.join('[' + ', '.join('"%s"' % w for w in ws) + ']' for ws in wordlists) + ']'
        sp = os.path.join(td, 's.g')
        open(sp, 'w').write(GAP % (N, outp, gl))
        subprocess.run(['gap', '-q', '-b', sp], check=True, capture_output=True, timeout=7200,
                       stdin=subprocess.DEVNULL)
        res = [json.loads(l) for l in open(outp) if l.strip()]
    return [{ch: [x - 1 for x in r[ch]] for ch in 'abc'} | {'d': r['d']} for r in res]


lines = []
P = lines.append
for fam in FAMILIES:
    N = int(fam.split('_N')[1])
    res = json.load(open('groups/%s_results.json' % fam))
    records = []
    for r in res:
        records.append(r)
        if r.get('double_cover'):
            records.append(r['double_cover'])
    key_of = {}
    for r in records:
        key_of.setdefault(tuple(map(tuple, r['key'])), []).append(r['label'])
    jobs = [(r, j) for r in records for j in range(len(r['packings']))]
    acts = coset_actions(N, [[reduce_word(w) for w in r['packings'][j]['words']] for r, j in jobs])
    nontrans, ident, unknown = [], set(), []
    by_surface = {}
    for (r, j), act in zip(jobs, acts):
        assert act['d'] == r['d'], (r['label'], j)
        k = canonical_key(act, act['d'])
        own = tuple(map(tuple, r['key']))
        by_surface.setdefault(r['label'], []).append(k == own)
        if k != own:
            others = key_of.get(k)
            if others is None:
                unknown.append(r['label'])
            else:
                ident.add(tuple(sorted([r['label']] + others)))
    for label, flags in by_surface.items():
        if not all(flags):
            nontrans.append('%s (%d of %d packings in the orbit of the packing centred at O)' % (
                label, sum(flags), len(flags)))
    n_two = sum(1 for flags in by_surface.values() if len(flags) >= 2)
    ncov = sum(1 for r in res if r.get('double_cover'))
    P('%-10s surfaces=%3d (+%2d double covers)  with >=2 packings=%3d  isometry group not transitive on packings: %s'
      % (fam, len(res), ncov, n_two, nontrans if nontrans else 'none'))
    P('%-10s different classes giving isometric surfaces: %s%s' % (
        '', sorted(ident) if ident else 'none', ('   K_j in no listed class: %s' % unknown) if unknown else ''))
open('groups/isometry_orbits.txt', 'w').write('\n'.join(lines) + '\n')
print('\n'.join(lines))
